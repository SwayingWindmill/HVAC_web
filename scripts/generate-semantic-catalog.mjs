// Generates the Operations Agent's semantic query whitelist (#573) from the Cube model: each public
// view's measures and groupable dimensions, with the Chinese titles and descriptions the cubes give
// them. The query service embeds the JSON, the Agent the TypeScript module; --check fails when either
// no longer matches the model.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import yaml from 'js-yaml';

const root = resolve(import.meta.dirname, '..');
const modelDir = resolve(root, 'semantic/cube/model');
const jsonPath = resolve(root, 'libs/analyticsmodel/semantic_catalog.json');
const tsPath = resolve(root, 'services/operations-agent-service/src/tools/internal/semantic-catalog.gen.ts');
// The Site comes from the Session's grant and time from the granularity and range, never from the model.
const forced = new Set(['site_id', 'period_end']);
// Freshness is not a figure to ask for: every answer's metadata already carries the watermark and revision.
const freshness = new Set(['max_data_watermark', 'max_dataset_revision']);
const timeDimension = 'period_end';

const load = (dir, key) => readdirSync(resolve(modelDir, dir)).filter((file) => file.endsWith('.yml')).sort()
  .flatMap((file) => yaml.load(readFileSync(resolve(modelDir, dir, file), 'utf8'))[key] ?? []);
const cubes = new Map(load('cubes', 'cubes').map((cube) => [cube.name, cube]));

// A member as the cube or the cube it extends defines it.
function member(cubeName, name) {
  for (let cube = cubes.get(cubeName); cube; cube = cube.extends ? cubes.get(cube.extends) : undefined) {
    const measure = (cube.measures ?? []).find((each) => each.name === name);
    if (measure) return { kind: 'measure', ...measure };
    const dimension = (cube.dimensions ?? []).find((each) => each.name === name);
    if (dimension) return { kind: dimension.type === 'time' ? 'time' : 'dimension', ...dimension };
  }
  throw new Error(`${cubeName}.${name} is not defined`);
}

const views = load('views', 'views').map((view) => {
  const members = view.cubes.flatMap((entry) => entry.includes.map((name) => member(entry.join_path, name)));
  if (!members.some((each) => each.kind === 'time' && each.name === timeDimension)) throw new Error(`${view.name} has no ${timeDimension}`);
  const describe = ({ name, title, description }) => ({ name, title, description: description.trim() });
  return {
    name: view.name,
    title: view.title,
    description: view.description.trim(),
    measures: members.filter((each) => each.kind === 'measure' && !freshness.has(each.name)).map(describe),
    dimensions: members.filter((each) => each.kind === 'dimension' && !forced.has(each.name)).map(describe),
  };
}).sort((left, right) => left.name.localeCompare(right.name));

const catalog = { schemaVersion: 1, timeDimension, views };
const json = `${JSON.stringify(catalog, null, 2)}\n`;
const ts = `// Generated by scripts/generate-semantic-catalog.mjs from semantic/cube/model; do not edit.\nexport const semanticCatalog = ${JSON.stringify(catalog, null, 2)} as const;\n`;

if (process.argv.includes('--check')) {
  const stale = [[jsonPath, json], [tsPath, ts]].filter(([path, content]) => {
    try { return readFileSync(path, 'utf8') !== content; } catch { return true; }
  });
  if (stale.length) {
    console.error(`Semantic catalog is stale: ${stale.map(([path]) => path).join(', ')}. Run npm run semantic:catalog:generate.`);
    process.exit(1);
  }
  console.log('Semantic catalog matches the Cube model.');
} else {
  writeFileSync(jsonPath, json);
  writeFileSync(tsPath, ts);
  console.log(`Generated the semantic catalog: ${views.length} views.`);
}
