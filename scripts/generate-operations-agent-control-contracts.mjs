import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const catalogPath = 'contracts/operations-agent/tool-catalog.v1.json';
const schemaPath = 'contracts/operations-agent/trusted-runtime-context.v1.schema.json';
const readText = (path) => readFileSync(join(root, path), 'utf8');
const readJson = (path) => JSON.parse(readText(path));
const quote = JSON.stringify;
const tuple = (values) => values.map((value) => `  ${quote(value)},`).join('\n');
const same = (left, right) => left.length === right.length && left.every((value, index) => value === right[index]);
const normalizeLineEndings = (value) => value.replace(/\r\n?/gu, '\n');
const exactKeys = (value, expected, label) => {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error(`${label} must be an object.`);
  const actual = Object.keys(value).sort();
  const wanted = [...expected].sort();
  if (!same(actual, wanted)) throw new Error(`${label} keys must be exactly ${wanted.join(', ')}.`);
};

const loadContracts = () => {
  const catalog = readJson(catalogPath);
  const schema = readJson(schemaPath);
  exactKeys(catalog, ['schemaVersion', 'catalogVersion', 'tools'], catalogPath);
  if (catalog.schemaVersion !== 1 || catalog.catalogVersion !== 'operations-agent-tool-catalog/v1') {
    throw new Error(`${catalogPath} has an unsupported version.`);
  }
  if (!Array.isArray(catalog.tools) || catalog.tools.length === 0) throw new Error(`${catalogPath} must contain tools.`);
  const toolKeys = ['logicalTool', 'ownerService', 'receiptOwner', 'benchmarkAllowed', 'runtimeReadAllowed', 'toolAuthorizationSupported'];
  const names = new Set();
  for (const [index, tool] of catalog.tools.entries()) {
    exactKeys(tool, toolKeys, `${catalogPath} tools[${index}]`);
    if (typeof tool.logicalTool !== 'string' || !/^[a-z][A-Za-z0-9]*(?:\.[A-Za-z0-9]+)+$/u.test(tool.logicalTool)) {
      throw new Error(`${catalogPath} tools[${index}].logicalTool is invalid.`);
    }
    if (names.has(tool.logicalTool)) throw new Error(`${catalogPath} contains duplicate tool ${tool.logicalTool}.`);
    names.add(tool.logicalTool);
    if (typeof tool.ownerService !== 'string' || tool.ownerService.length === 0) throw new Error(`Owner is missing for ${tool.logicalTool}.`);
    if (tool.receiptOwner !== null && typeof tool.receiptOwner !== 'string') throw new Error(`receiptOwner is invalid for ${tool.logicalTool}.`);
    for (const key of ['benchmarkAllowed', 'runtimeReadAllowed', 'toolAuthorizationSupported']) {
      if (typeof tool[key] !== 'boolean') throw new Error(`${key} must be boolean for ${tool.logicalTool}.`);
    }
    if (tool.runtimeReadAllowed && tool.receiptOwner === null) throw new Error(`Runtime READ tool ${tool.logicalTool} must define receiptOwner.`);
    if (tool.toolAuthorizationSupported && !tool.runtimeReadAllowed) throw new Error(`Authorization tool ${tool.logicalTool} must be a Runtime READ tool.`);
  }
  const runtimeTools = catalog.tools.filter((tool) => tool.runtimeReadAllowed);
  const benchmarkTools = catalog.tools.filter((tool) => tool.benchmarkAllowed);
  const authorizationTools = catalog.tools.filter((tool) => tool.toolAuthorizationSupported);
  const schemaTools = schema?.properties?.allowedReadTools?.items?.enum;
  if (!Array.isArray(schemaTools) || !same(schemaTools, runtimeTools.map((tool) => tool.logicalTool))) {
    throw new Error(`${schemaPath} allowedReadTools must match runtimeReadAllowed catalog order.`);
  }
  if (schema.additionalProperties !== false || schema?.properties?.scope?.additionalProperties !== false) {
    throw new Error(`${schemaPath} must reject additional context and scope properties.`);
  }
  return { catalog, schema, runtimeTools, benchmarkTools, authorizationTools };
};

const renderDomain = ({ catalog, runtimeTools }) => {
  const owners = [...new Set(runtimeTools.map((tool) => tool.receiptOwner))];
  const ownerMap = runtimeTools.map((tool) => `  ${quote(tool.logicalTool)}: ${quote(tool.receiptOwner)},`).join('\n');
  return `// Generated by scripts/generate-operations-agent-control-contracts.mjs. Do not edit.\n\nexport const OPERATIONS_AGENT_TOOL_CATALOG_VERSION = ${quote(catalog.catalogVersion)} as const;\n\nexport const OPERATIONS_AGENT_RUNTIME_READ_TOOLS = [\n${tuple(runtimeTools.map((tool) => tool.logicalTool))}\n] as const;\n\nexport type LogicalTool = typeof OPERATIONS_AGENT_RUNTIME_READ_TOOLS[number];\n\nexport const OPERATIONS_AGENT_TOOL_RECEIPT_OWNERS = [\n${tuple(owners)}\n] as const;\n\nexport type ToolOwner = typeof OPERATIONS_AGENT_TOOL_RECEIPT_OWNERS[number];\n\nexport const OPERATIONS_AGENT_TOOL_RECEIPT_OWNER_BY_LOGICAL_TOOL = Object.freeze({\n${ownerMap}\n} as const satisfies Readonly<Record<LogicalTool, ToolOwner>>);\n`;
};

const renderRuntime = ({ schema }) => {
  const properties = schema.properties;
  return `// Generated by scripts/generate-operations-agent-control-contracts.mjs. Do not edit.\n\nexport const OPERATIONS_AGENT_TRUSTED_RUNTIME_CONTEXT_ID = ${quote(schema.$id)} as const;\n\nexport const OPERATIONS_AGENT_TRUSTED_RUNTIME_CONTEXT_KEYS = [\n${tuple(schema.required)}\n] as const;\n\nexport const OPERATIONS_AGENT_TRUSTED_RUNTIME_SCOPE_KEYS = [\n${tuple(properties.scope.required)}\n] as const;\n\nexport const OPERATIONS_AGENT_TRUSTED_RUNTIME_MAXIMUM_IDENTITY_CHARACTERS = ${properties.investigationId.maxLength} as const;\n\nexport const OPERATIONS_AGENT_TRUSTED_RUNTIME_CONTROL_POLICY = Object.freeze({\n  schemaVersion: ${properties.schemaVersion.const},\n  source: ${quote(properties.source.const)},\n  trust: ${quote(properties.trust.const)},\n  runStatus: ${quote(properties.runStatus.const)},\n  effectPolicy: ${quote(properties.effectPolicy.const)},\n  scopePolicy: ${quote(properties.scopePolicy.const)},\n  untrustedContentPolicy: ${quote(properties.untrustedContentPolicy.const)},\n} as const);\n`;
};

const renderBenchmark = ({ catalog, benchmarkTools, runtimeTools, authorizationTools }) => {
  const entries = benchmarkTools.map((tool) => `  ${quote(tool.logicalTool)}: ${quote(tool.ownerService)},`).join('\n');
  return `// Generated by scripts/generate-operations-agent-control-contracts.mjs. Do not edit.\n\nexport const OPERATIONS_AGENT_TOOL_CATALOG_VERSION = ${quote(catalog.catalogVersion)};\n\nexport const OPERATIONS_AGENT_TOOL_CATALOG = Object.freeze({\n${entries}\n});\n\nexport const OPERATIONS_AGENT_RUNTIME_READ_TOOLS = Object.freeze([\n${tuple(runtimeTools.map((tool) => tool.logicalTool))}\n]);\n\nexport const OPERATIONS_AGENT_TOOL_AUTHORIZATION_TOOLS = Object.freeze([\n${tuple(authorizationTools.map((tool) => tool.logicalTool))}\n]);\n`;
};

const renderWeb = ({ catalog, runtimeTools }) => {
  const owners = [...new Set(runtimeTools.map((tool) => tool.receiptOwner))];
  return `// Generated by scripts/generate-operations-agent-control-contracts.mjs. Do not edit.\n\nexport const OPERATIONS_AGENT_TOOL_CATALOG_VERSION = ${quote(catalog.catalogVersion)} as const;\n\nexport const OPERATIONS_AGENT_RUNTIME_READ_TOOLS = [\n${tuple(runtimeTools.map((tool) => tool.logicalTool))}\n] as const;\n\nexport const OPERATIONS_AGENT_TOOL_RECEIPT_OWNERS = [\n${tuple(owners)}\n] as const;\n`;
};

const validateOpenApi = ({ runtimeTools, authorizationTools }) => {
  const publicContract = readText('contracts/http/operations-investigations-public.openapi.yaml');
  const match = /logicalTool:\s*\{[^}\n]*enum:\s*\[([^\]]+)\][^}\n]*\}/u.exec(publicContract);
  if (!match) throw new Error('Public Operations OpenAPI is missing the logicalTool enum.');
  const publicTools = match[1].split(',').map((value) => value.trim()).filter(Boolean);
  if (!same(publicTools, runtimeTools.map((tool) => tool.logicalTool))) {
    throw new Error('Public Operations OpenAPI logicalTool enum drifted from the v1 tool catalog.');
  }
  const authorizationContract = readText('contracts/http/operations-tool-authorization-internal.openapi.yaml');
  const actual = [...authorizationContract.matchAll(/tool:\s*\{\s*const:\s*([A-Za-z0-9._-]+)\s*\}/gu)].map((item) => item[1]);
  if (!same(actual, authorizationTools.map((tool) => tool.logicalTool))) {
    throw new Error('Tool Authorization OpenAPI variants drifted from the v1 tool catalog.');
  }
};

const contracts = loadContracts();
validateOpenApi(contracts);
const outputs = new Map([
  ['services/operations-agent-service/src/domain/internal/generated-tool-contract.ts', renderDomain(contracts)],
  ['services/operations-agent-service/src/application/internal/generated-runtime-control-contract.ts', renderRuntime(contracts)],
  ['benchmarks/operations-agent/generated/tool-catalog.v1.mjs', renderBenchmark(contracts)],
  ['apps/hvac-web/src/api/generated/operations-tool-contract.ts', renderWeb(contracts)],
]);
const drift = [];
for (const [path, content] of outputs) {
  const absolutePath = join(root, path);
  if (checkOnly) {
    let current = '';
    try { current = readFileSync(absolutePath, 'utf8'); } catch { current = ''; }
    if (normalizeLineEndings(current) !== normalizeLineEndings(content)) drift.push(path);
  } else {
    mkdirSync(dirname(absolutePath), { recursive: true });
    writeFileSync(absolutePath, content, 'utf8');
  }
}
if (drift.length > 0) throw new Error(`Generated Operations Agent control contracts drifted:\n- ${drift.join('\n- ')}`);
console.log(`${checkOnly ? 'Checked' : 'Generated'} ${outputs.size} Operations Agent control contract artifacts.`);
